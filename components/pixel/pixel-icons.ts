export type PixelIconName = keyof typeof pixelIcons;

export type PixelRect = { x: number; y: number; width: number };

/** Merge horizontal runs of filled pixels into rects (fewer SVG nodes). */
export function toRects(rows: readonly string[]): PixelRect[] {
  const rects: PixelRect[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x += 1) {
      const filled = row[x] === "#";
      if (filled && start === -1) start = x;
      if (!filled && start !== -1) {
        rects.push({ x: start, y, width: x - start });
        start = -1;
      }
    }
  });
  return rects;
}
